--
-- NULL 을 허용한다. 슬랙에는 리스트에 열을 나중에 추가하는 API 가 없어서 이
-- 변경 전에 만들어진 리스트는 그 열을 영영 갖지 못한다. 그런 행은 NULL 로
-- 남고, 코드가 예전처럼 제목 칸에 링크를 붙인다.

